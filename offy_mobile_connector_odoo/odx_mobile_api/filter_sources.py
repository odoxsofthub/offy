"""Filter definitions, one class per filterable list, used by the `/filters*` dispatchers.
Add an option via `OPTIONS` plus its methods, or a new list via a class plus a `FILTER_SOURCES` entry."""

import calendar
from datetime import date

from odoo.http import request

# "Recent" counts months that have data, not "this year", so January users can reach December.
RECENT_MONTH_COUNT = 12

MONTH_KEY_FORMAT = "%Y-%m"


def month_key(value):
    """`date(2026, 9, 4)` -> `"2026-09"`. The id of a month selection."""
    return value.strftime(MONTH_KEY_FORMAT)


def month_label(value):
    """`date(2026, 9, 4)` -> `"Sep 2026"`, matching the app's month chips."""
    return "%s %s" % (calendar.month_abbr[value.month], value.year)


def parse_month_key(value):
    """`"2026-09"` -> `(2026, 9)`, or None when it is not a month key.
    Strict on purpose: month ids are generated by this API and echoed back."""
    if not isinstance(value, str):
        return None
    parts = value.split("-")
    if len(parts) != 2:
        return None
    try:
        year, month = int(parts[0]), int(parts[1])
    except (TypeError, ValueError):
        return None
    if not (1 <= month <= 12) or not (1900 <= year <= 9999):
        return None
    return year, month


def _parse_date(value):
    """`"2026-09-12"` -> `date`, or None.
    Local copy to avoid an import cycle with the controllers package."""
    if not isinstance(value, str):
        return None
    try:
        return date.fromisoformat(value.strip())
    except (TypeError, ValueError):
        return None


def month_bounds(year, month):
    last_day = calendar.monthrange(year, month)[1]
    return date(year, month, 1), date(year, month, last_day)


def timeline_label(value):
    """`date(2026, 9, 4)` -> `"September 2026"`, the month group heading."""
    return "%s %s" % (calendar.month_name[value.month], value.year)


def range_label(start, end):
    """Heading for a custom date range, e.g. `"Sep 12 - Dec 14, 2026"`.
    Shared year/month parts are written once; a one-day range is just that day."""
    if start == end:
        return "%s %s, %s" % (calendar.month_abbr[start.month], start.day, start.year)
    if start.year != end.year:
        return "%s %s, %s - %s %s, %s" % (
            calendar.month_abbr[start.month], start.day, start.year,
            calendar.month_abbr[end.month], end.day, end.year)
    if start.month == end.month:
        return "%s %s - %s, %s" % (
            calendar.month_abbr[start.month], start.day, end.day, start.year)
    return "%s %s - %s %s, %s" % (
        calendar.month_abbr[start.month], start.day,
        calendar.month_abbr[end.month], end.day, start.year)


def group_by_timeline(records, payloads, date_field, key, bounds=None):
    """Bucket an already-paginated page into `[{"timeline": .., key: [..]}]`.
    One group for a custom range (*bounds*), else by month; *records* must be ordered by *date_field* and parallel to *payloads*."""
    if not records:
        return []
    if bounds:
        return [{"timeline": range_label(*bounds), key: list(payloads)}]
    groups = []
    current = object()
    for record, payload in zip(records, payloads):
        value = record[date_field]
        month = (value.year, value.month) if value else None
        if month != current:
            groups.append({
                "timeline": timeline_label(value) if value else "Undated",
                key: [],
            })
            current = month
        groups[-1][key].append(payload)
    return groups


def any_of(windows, field="date"):
    """OR together `(start, end)` windows on *field* as an Odoo domain.
    Centralised because a wrong count of prefix "|" operators silently matches wrong rows."""
    if not windows:
        return []
    domain = ["|"] * (len(windows) - 1)
    for start, end in windows:
        domain += ["&", (field, ">=", start), (field, "<=", end)]
    return domain


class FilterError(Exception):
    """A rejected filter request. Carries the API error code and message."""

    def __init__(self, code, message, status=400):
        super().__init__(message)
        self.code = code
        self.message = message
        self.status = status


class FilterSource:
    """Shared month picker, apply/clear conventions and active-state payload for a filterable list.
    Add an option via `OPTIONS` plus `apply_<option>` (and `values_<option>`); handlers find them by name."""

    code = None
    feature = None
    model = None
    # Must be the column the listing ORDERS by, or a month bucket can hold rows the list never shows.
    date_field = None

    # Lists this source presents; empty means a single list, stored as "" in `view`.
    VIEWS = ()

    MENU_OPTIONS = ()
    OPTIONS = ()
    OPTION_LABELS = {}
    OPTION_SELECTION = {}
    PAYLOAD_KEYS = {
        "category": "category_ids",
        "month": "month_ids",
        "status": "status_ids",
        "leave_type": "leave_type_ids",
    }
    # Options cleared when `month` is applied (only expense has a date range to clear).
    MONTH_CLEARS = ()

    def __init__(self, user, view=""):
        self.user = user
        self.employee = user.employee_id
        # "" for a single-list source; the dispatch guarantees multi-view sources get a real view.
        self.view = view or ""

    def base_domain(self):
        """Every value list is scoped to the caller's own records.
        So the panel never offers a month that would select nothing."""
        return [("employee_id", "=", self.employee.id)]

    def _dates(self):
        """Every date the caller has a record on, newest first."""
        rows = request.env[self.model].search_read(
            self.base_domain(), [self.date_field],
            order="%s desc" % self.date_field)
        return [row[self.date_field] for row in rows if row.get(self.date_field)]

    @staticmethod
    def _status_maps():
        """`(mobile status -> [odoo states], mobile status -> label)` from the expense controller.
        Imported at call time to avoid an import cycle; keeps filter statuses identical to row badges."""
        from .controllers.expense import STATUS_MAP, STATUS_DISPLAY
        states_by_status = {}
        for state, status in STATUS_MAP.items():
            states_by_status.setdefault(status, []).append(state)
        return states_by_status, STATUS_DISPLAY

    def values_status(self, params):
        """Every status an expense row can show, in lifecycle order.
        The full fixed catalogue, so the panel does not rearrange as claims move."""
        states_by_status, labels = self._status_maps()
        order = ("draft", "pending", "approved", "paid", "refused")
        return {
            "option": "status",
            "selection": "multi",
            "items": [{"id": status, "label": labels.get(status, status.title())}
                      for status in order if status in states_by_status],
        }

    def apply_status(self, payload):
        """`{"status_ids": ["approved"]}`. None / missing / [] clear.
        Ids are mobile statuses as rendered, not Odoo state names."""
        raw = payload.get("status_ids")
        if raw is None or raw == []:
            return "status", None, ()
        if not isinstance(raw, list):
            raise FilterError("invalid_status_ids",
                              "status_ids must be a list of statuses or null.")
        known = self._status_maps()[0]
        statuses = []
        for item in raw:
            if not isinstance(item, str) or item not in known:
                raise FilterError(
                    "invalid_status_ids",
                    "status_ids must be one of %s; got %r."
                    % (", ".join(sorted(known)), item))
            if item not in statuses:
                statuses.append(item)
        return "status", sorted(statuses), ()

    def values_month(self, params):
        dates = self._dates()
        bucket = (params.get("bucket") or "").strip()
        if not bucket:
            years = sorted({d.year for d in dates}, reverse=True)
            buckets = [{"key": "recent", "label": "Recent"}]
            buckets += [{"key": str(y), "label": str(y)} for y in years]
            return {
                "option": "month",
                "level": "bucket",
                "buckets": buckets,
                "custom_range_available": "date_range" in self.OPTIONS,
            }

        if bucket == "recent":
            keys = []
            for value in dates:            # already newest-first
                key = month_key(value)
                if key not in keys:
                    keys.append(key)
                if len(keys) == RECENT_MONTH_COUNT:
                    break
        else:
            try:
                year = int(bucket)
            except (TypeError, ValueError):
                raise FilterError(
                    "invalid_bucket",
                    "bucket must be 'recent' or a four-digit year.")
            keys = []
            for value in dates:
                if value.year != year:
                    continue
                key = month_key(value)
                if key not in keys:
                    keys.append(key)

        items = []
        for key in keys:
            year, month = parse_month_key(key)
            items.append({"id": key, "label": month_label(date(year, month, 1))})
        return {
            "option": "month",
            "level": "month",
            "bucket": bucket,
            "items": items,
        }

    def apply_month(self, payload):
        """`{"month_ids": ["2026-09"]}`. None / missing / [] clear."""
        raw = payload.get("month_ids")
        if raw is None or raw == []:
            return "month", None, self.MONTH_CLEARS
        if not isinstance(raw, list):
            raise FilterError("invalid_month_ids",
                              "month_ids must be a list of YYYY-MM strings or null.")
        keys = []
        for item in raw:
            if not parse_month_key(item):
                raise FilterError(
                    "invalid_month_ids",
                    "month_ids must be YYYY-MM strings; got %r." % (item,))
            if item not in keys:
                keys.append(item)
        return "month", sorted(keys, reverse=True), self.MONTH_CLEARS

    def month_domain(self, keys):
        """Selected months as an OR of date windows, on `date_field`."""
        windows = []
        for key in keys or ():
            parsed = parse_month_key(key)
            if parsed:
                windows.append(month_bounds(*parsed))
        return any_of(windows, self.date_field)

    def search_domain(self, term):
        """Domain matching *term*, or [] for a source with no search.
        Search is a transient `?search=` parameter, never part of the stored filter."""
        return []

    def apply_date_range(self, payload):
        """`{"from_date": "...", "to_date": "..."}`. Both null/missing clear; a half-filled range is rejected.
        Clears `month`, the other half of the mutual exclusion."""
        raw_from = payload.get("from_date")
        raw_to = payload.get("to_date")
        if raw_from in (None, "") and raw_to in (None, ""):
            return "date_range", None, ("month",)
        if raw_from in (None, "") or raw_to in (None, ""):
            raise FilterError(
                "invalid_date_range",
                "from_date and to_date must both be set, or both be null.")

        parsed_from = _parse_date(raw_from)
        parsed_to = _parse_date(raw_to)
        if not parsed_from or not parsed_to:
            raise FilterError("invalid_date_range",
                              "from_date and to_date must be YYYY-MM-DD dates.")
        if parsed_to < parsed_from:
            raise FilterError("invalid_date_range",
                              "to_date must not be earlier than from_date.")
        return "date_range", {"from": parsed_from.isoformat(),
                              "to": parsed_to.isoformat()}, ("month",)

    @staticmethod
    def range_bounds(state):
        """`(from, to)` when a custom range is active, else None.
        Decides between one range-headed group and month grouping."""
        date_range = state.get("date_range")
        if not date_range:
            return None
        parsed_from = _parse_date(date_range.get("from"))
        parsed_to = _parse_date(date_range.get("to"))
        if not parsed_from or not parsed_to:
            return None
        return parsed_from, parsed_to

    @staticmethod
    def active_date_range(state):
        date_range = state.get("date_range") or None
        return {"date_range": ({"from_date": date_range["from"],
                                "to_date": date_range["to"]}
                               if date_range else None)}

    def domain_from_state(self, state):
        """Extra domain leaves for the active filters (months plus free text).
        Sources extend rather than replace this, so shared options reach every source."""
        leaves = []
        bounds = self.range_bounds(state)
        if bounds:
            # A custom range wins over months; hand-written rows must not AND two disjoint windows.
            leaves.append((self.date_field, ">=", bounds[0]))
            leaves.append((self.date_field, "<=", bounds[1]))
        else:
            leaves += self.month_domain(state.get("month"))
        # `state["search"]` is intentionally ignored; legacy rows may still carry the key.
        return leaves

    def active_payload(self, state):
        """The active filters, in the shape the client sent them.
        Driven by `OPTIONS`, so new options show as active without a second edit."""
        payload = {}
        for option in self.OPTIONS:
            renderer = getattr(self, "active_%s" % option, None)
            if renderer is not None:
                payload.update(renderer(state))
                continue
            key = self.PAYLOAD_KEYS[option]
            payload[key] = state.get(option) or []
        return payload


class ExpenseFilterSource(FilterSource):
    """Filters for `GET /api/mobile/v1/expense`: category, status, month and date_range.
    `month` and `date_range` are mutually exclusive, enforced by `mobile.list.filter.set_option(clears=...)`."""

    code = "expense"
    feature = "expense"
    model = "hr.expense"
    date_field = "date"
    # Applying months clears a custom range; the panel presents them as alternatives.
    MONTH_CLEARS = ("date_range",)
    MENU_OPTIONS = ("category", "status", "month")
    OPTIONS = ("category", "status", "month", "date_range")
    OPTION_LABELS = {
        "category": "Categories",
        "status": "Status",
        "month": "Months",
        "date_range": "Custom Date Range",
    }
    OPTION_SELECTION = {
        "category": "multi",
        "status": "multi",
        "month": "multi",
        "date_range": "range",
    }

    def values_category(self, params):
        """Every expense category, not only the ones already used.
        Same domain and order as `GET /expense/categories` so the panel and picker agree."""
        categories = request.env["product.product"].search(
            [("can_be_expensed", "=", True)], order="name asc")
        return {
            "option": "category",
            "selection": "multi",
            "items": [{"id": c.id, "label": c.name} for c in categories],
        }

    def apply_category(self, payload):
        """`{"category_ids": [...]}`. None / missing / [] all clear.
        An empty list means "no category filter", not "match nothing"."""
        raw = payload.get("category_ids")
        if raw is None or raw == []:
            return "category", None, ()
        if not isinstance(raw, list):
            raise FilterError("invalid_category_ids",
                              "category_ids must be a list of integers or null.")
        ids = []
        for item in raw:
            if isinstance(item, bool) or not isinstance(item, int):
                try:
                    item = int(item)
                except (TypeError, ValueError):
                    raise FilterError(
                        "invalid_category_ids",
                        "category_ids must be a list of integers or null.")
            ids.append(item)
        return "category", sorted(set(ids)), ()

    def domain_from_state(self, state):
        """The shared leaves plus category and status, which AND together.
        A status expands to every Odoo state behind it; `["__none__"]` avoids an empty `in []` matching everything."""
        leaves = super().domain_from_state(state)
        categories = state.get("category")
        if categories:
            leaves.append(("product_id", "in", categories))
        statuses = state.get("status")
        if statuses:
            states_by_status = self._status_maps()[0]
            wanted = []
            for status in statuses:
                wanted += states_by_status.get(status, [])
            leaves.append(("state", "in", wanted or ["__none__"]))
        return leaves


class TimeoffFilterSource(FilterSource):
    """Filters for `/timeoff/upcoming` and `/timeoff/history`, stored separately per `view`.
    Options: month, date_range (on `request_date_from`), mobile status and leave_type; they AND together."""

    code = "timeoff"
    feature = "time_off"
    # Upcoming and history are separate lists, so each has its own filter set.
    VIEWS = ("upcoming", "history")
    model = "hr.leave"
    # Must match the column both listings order by (see `date_field` on the base).
    date_field = "request_date_from"

    # `date_range` is applied from the month panel (via `custom_range_available`), not a menu entry.
    MENU_OPTIONS = ("month", "status", "leave_type")
    OPTIONS = ("month", "status", "leave_type", "date_range")
    MONTH_CLEARS = ("date_range",)
    OPTION_LABELS = {
        "month": "Months",
        "status": "Status",
        "leave_type": "Leave Type",
        "date_range": "Custom Date Range",
    }
    OPTION_SELECTION = {
        "month": "multi",
        "status": "multi",
        "leave_type": "multi",
        "date_range": "range",
    }

    VIEW_DOMAINS = {
        "upcoming": "_upcoming_domain",
        "history": "_history_domain",
    }

    def base_domain(self):
        """The records this view lists, from which every value list is drawn.
        Reuses the listing's own domain and "today" so offered and listed values are the same set."""
        method = self.VIEW_DOMAINS.get(self.view)
        if not method:
            return super().base_domain()
        from odoo import fields
        from .controllers.timeoff import MobileApiTimeoff
        today = fields.Date.context_today(self.user)
        return getattr(MobileApiTimeoff(), method)(self.employee, today)

    def _occurring(self, field):
        """Distinct non-empty values of *field* across this view's records, in one grouped query."""
        rows = request.env[self.model]._read_group(
            self.base_domain(), [field], [])
        return [value for (value,) in rows if value]

    @staticmethod
    def _stage_maps():
        """`(stage -> [odoo states], stage -> label)` from the timeoff controller.
        Imported at call time to avoid an import cycle; keeps stages identical to row badges."""
        from .controllers.timeoff import STAGE_BY_STATE, STAGE_DISPLAY
        states_by_stage = {}
        for state, stage in STAGE_BY_STATE.items():
            states_by_stage.setdefault(stage, []).append(state)
        return states_by_stage, STAGE_DISPLAY

    def values_status(self, params):
        """The stages that occur among this view's leaves, in lifecycle order.
        Mapped through `STAGE_BY_STATE`, so `confirm` and `validate1` both surface as `pending`."""
        from .controllers.timeoff import STAGE_BY_STATE
        states_by_stage, labels = self._stage_maps()
        present = {STAGE_BY_STATE.get(state, state)
                   for state in self._occurring("state")}
        order = ("pending", "approved", "rejected", "cancelled")
        return {
            "option": "status",
            "selection": "multi",
            "items": [{"id": stage, "label": labels.get(stage, stage.title())}
                      for stage in order
                      if stage in states_by_stage and stage in present],
        }

    def apply_status(self, payload):
        """`{"status_ids": ["approved"]}`. None / missing / [] clear.
        Ids are the mobile stages the listing puts in a row's `stage`."""
        raw = payload.get("status_ids")
        if raw is None or raw == []:
            return "status", None, ()
        if not isinstance(raw, list):
            raise FilterError("invalid_status_ids",
                              "status_ids must be a list of stages or null.")
        known = self._stage_maps()[0]
        stages = []
        for item in raw:
            if not isinstance(item, str) or item not in known:
                raise FilterError(
                    "invalid_status_ids",
                    "status_ids must be one of %s; got %r."
                    % (", ".join(sorted(known)), item))
            if item not in stages:
                stages.append(item)
        return "status", sorted(stages), ()

    def values_leave_type(self, params):
        """The leave types that occur among this view's leaves, sorted by name.
        Not the requestable types, so past types with history remain filterable."""
        types = request.env["hr.leave.type"].browse(
            sorted({t.id for t in self._occurring("holiday_status_id")}))
        return {
            "option": "leave_type",
            "selection": "multi",
            "items": [{"id": t.id, "label": t.name}
                      for t in types.sorted(lambda t: (t.name or "").lower())],
        }

    def apply_leave_type(self, payload):
        """`{"leave_type_ids": [3]}`. None / missing / [] clear."""
        raw = payload.get("leave_type_ids")
        if raw is None or raw == []:
            return "leave_type", None, ()
        if not isinstance(raw, list):
            raise FilterError("invalid_leave_type_ids",
                              "leave_type_ids must be a list of integers or null.")
        ids = []
        for item in raw:
            if isinstance(item, bool) or not isinstance(item, int):
                try:
                    item = int(item)
                except (TypeError, ValueError):
                    raise FilterError(
                        "invalid_leave_type_ids",
                        "leave_type_ids must be a list of integers or null.")
            ids.append(item)
        return "leave_type", sorted(set(ids)), ()

    def search_domain(self, term):
        """Match the leave type name or the reason.
        `private_name` is group-restricted, so matching ids come from a sudo lookup pinned to this employee."""
        by_type = [("holiday_status_id.name", "ilike", term)]
        reason_ids = request.env["hr.leave"].sudo().search([
            ("employee_id", "=", self.employee.id),
            ("private_name", "ilike", term),
        ]).ids
        if not reason_ids:
            return by_type
        return ["|"] + by_type + [("id", "in", reason_ids)]

    def domain_from_state(self, state):
        leaves = super().domain_from_state(state)
        states_by_stage = self._stage_maps()[0]
        stages = state.get("status")
        if stages:
            wanted = []
            for stage in stages:
                wanted += states_by_stage.get(stage, [])
            leaves.append(("state", "in", wanted or ["__none__"]))
        types = state.get("leave_type")
        if types:
            leaves.append(("holiday_status_id", "in", types))
        return leaves


class PayslipFilterSource(FilterSource):
    """Filters for `GET /api/mobile/v1/payslip/list`: month only."""

    code = "payslip"
    feature = "payslip"
    model = "hr.payslip"
    # `date_to` is what the list orders by and cuts year sections on, so months must use it too.
    date_field = "date_to"

    MENU_OPTIONS = ("month",)
    OPTIONS = ("month",)
    OPTION_LABELS = {"month": "Months"}
    OPTION_SELECTION = {"month": "multi"}

    def base_domain(self):
        """Only the payslips the list itself shows.
        The listing reads with sudo() and re-scopes by company, so buckets must use the same visible set."""
        from .controllers.payslip import VISIBLE_STATES
        return [
            ("employee_id", "=", self.employee.id),
            ("state", "in", list(VISIBLE_STATES)),
        ]

    def _dates(self):
        # sudo() as the listing does; the domain stays pinned to this employee from the token.
        rows = request.env[self.model].sudo().search_read(
            self.base_domain(), [self.date_field],
            order="%s desc" % self.date_field)
        return [row[self.date_field] for row in rows if row.get(self.date_field)]

    def search_domain(self, term):
        """Match the payslip reference, or the displayed period when *term* names a month.
        `period` is rendered from `date_from`, so it is matched via month windows, not `ilike`."""
        parts = [("name", "ilike", term)]
        windows = self._month_name_windows(term)
        if not windows:
            return parts
        return ["|"] + parts + any_of(windows, self.date_field)

    def _month_name_windows(self, term):
        """Windows for every month with data that *term* names ("jun", "June 2026").
        A bare year is left to the `name ilike` half to avoid widening it to a whole year."""
        needle = " ".join(term.lower().split())
        if len(needle) < 3:
            return []
        windows = []
        for value in self._dates():
            if not self._names_month(needle, value):
                continue
            window = month_bounds(value.year, value.month)
            if window not in windows:
                windows.append(window)
        return windows

    @staticmethod
    def _names_month(needle, value):
        """Whether lower-cased *needle* names the month of *value*.
        The month may be a prefix, but a given year must match exactly."""
        full = calendar.month_name[value.month].lower()
        abbr = calendar.month_abbr[value.month].lower()
        if full.startswith(needle) or abbr.startswith(needle):
            return True
        month_part, _, year_part = needle.rpartition(" ")
        if not month_part:
            return False
        return (year_part == str(value.year)
                and (full.startswith(month_part) or abbr.startswith(month_part)))


FILTER_SOURCES = {
    ExpenseFilterSource.code: ExpenseFilterSource,
    TimeoffFilterSource.code: TimeoffFilterSource,
    PayslipFilterSource.code: PayslipFilterSource,
}
